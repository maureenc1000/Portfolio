/*
Bob's Fixit: transactional database (SQL Server)
------------------------------------------------
Bob runs a small home repair business. These tables track customers, bids, repairs,
materials, suppliers, invoices and payments.

Run the scripts in order: 01 creates the tables, 02 adds sample data, 03 answers the
business questions. 04 and 05 build and query a small star schema for reporting.
Tables are dropped first (children before parents) so the script can be rerun.
*/

SET QUOTED_IDENTIFIER ON;   -- required for the persisted computed column in BIDS (on by default in SSMS)
GO

DROP VIEW  IF EXISTS CUSTOMER_BALANCES;
DROP VIEW  IF EXISTS SUPPLIER_BALANCES;
DROP TABLE IF EXISTS MATERIAL_SUPPLIER;
DROP TABLE IF EXISTS MATERIALS;
DROP TABLE IF EXISTS REPAIRS;
DROP TABLE IF EXISTS SUPPLIER_PAYMENTS;
DROP TABLE IF EXISTS SUPPLIERS;
DROP TABLE IF EXISTS INVOICES;
DROP TABLE IF EXISTS CUSTOMER_PAYMENTS;
DROP TABLE IF EXISTS BIDS;
DROP TABLE IF EXISTS CUSTOMERS;
GO

CREATE TABLE CUSTOMERS (
     CUSTOMER_ID      INT IDENTITY(1,1) PRIMARY KEY
    ,CUSTOMER_NAME    VARCHAR(100)
    ,CUSTOMER_EMAIL   VARCHAR(100)
    ,CUSTOMER_ADDRESS VARCHAR(1000)
    ,CUSTOMER_PHONE   VARCHAR(20)
);

CREATE TABLE BIDS (
     BID_ID        INT IDENTITY(1,1) PRIMARY KEY
    ,CUSTOMER_ID   INT FOREIGN KEY REFERENCES CUSTOMERS(CUSTOMER_ID)
    ,BID_DATE      DATE
    ,RATE_PER_HOUR MONEY
    ,MATERIAL_COST MONEY
    ,TOTAL_COST AS CAST((RATE_PER_HOUR + MATERIAL_COST) AS MONEY) PERSISTED   -- calculated column, stored
);

CREATE TABLE CUSTOMER_PAYMENTS (
     CUSTOMER_PAYMENT_ID INT IDENTITY(1,1) PRIMARY KEY
    ,CUSTOMER_ID         INT FOREIGN KEY REFERENCES CUSTOMERS(CUSTOMER_ID)
    ,PAYMENT_DATE        DATE
    ,PAYMENT_AMOUNT      MONEY
);

CREATE TABLE INVOICES (
     INVOICE_ID       INT IDENTITY(1,1) PRIMARY KEY
    ,CUSTOMER_ID      INT FOREIGN KEY REFERENCES CUSTOMERS(CUSTOMER_ID)
    ,INVOICE_DATE     DATE NOT NULL DEFAULT GETDATE()
    ,TOTAL_AMOUNT_DUE MONEY NOT NULL
);

CREATE TABLE SUPPLIERS (
     SUPPLIER_ID      INT IDENTITY(1,1) PRIMARY KEY
    ,SUPPLIER_NAME    VARCHAR(50)
    ,SUPPLIER_EMAIL   VARCHAR(100)
    ,SUPPLIER_ADDRESS VARCHAR(1000)
    ,SUPPLIER_PHONE   VARCHAR(20)
);

CREATE TABLE SUPPLIER_PAYMENTS (
     SUPPLIER_PAYMENT_ID INT IDENTITY(1,1) PRIMARY KEY
    ,SUPPLIER_ID         INT FOREIGN KEY REFERENCES SUPPLIERS(SUPPLIER_ID)
    ,PAYMENT_DATE        DATE
    ,PAYMENT_AMOUNT      MONEY
);

-- REPAIRS is created before MATERIALS because MATERIALS points to it
CREATE TABLE REPAIRS (
     REPAIR_ID          INT IDENTITY(1,1) PRIMARY KEY
    ,BID_ID             INT FOREIGN KEY REFERENCES BIDS(BID_ID)
    ,REPAIR_DESCRIPTION VARCHAR(200)
    ,REPAIR_HOURS       INT
    ,REPAIR_COST        MONEY
);

CREATE TABLE MATERIALS (
     MATERIAL_ID        INT IDENTITY(1,1) PRIMARY KEY
    ,REPAIR_ID          INT FOREIGN KEY REFERENCES REPAIRS(REPAIR_ID)
    ,SUPPLIER_ID        INT FOREIGN KEY REFERENCES SUPPLIERS(SUPPLIER_ID)
    ,MATERIAL_NAME      VARCHAR(150)
    ,MATERIAL_QTY       INT
    ,MATERIAL_UNIT_COST MONEY
);

-- which suppliers can provide which materials (many-to-many)
CREATE TABLE MATERIAL_SUPPLIER (
     SUPPLIER_ID INT FOREIGN KEY REFERENCES SUPPLIERS(SUPPLIER_ID)
    ,MATERIAL_ID INT FOREIGN KEY REFERENCES MATERIALS(MATERIAL_ID)
    ,PRIMARY KEY (SUPPLIER_ID, MATERIAL_ID)
);
GO

-- what each customer has been billed, has paid, and still owes Bob
-- (invoices and payments are totaled separately first, so a customer with several of each is not double counted)
CREATE VIEW CUSTOMER_BALANCES AS
SELECT
     C.CUSTOMER_ID
    ,C.CUSTOMER_NAME
    ,COALESCE(I.TOTAL_BILLED, 0)                               AS TOTAL_BILLED
    ,COALESCE(P.TOTAL_PAID, 0)                                 AS TOTAL_CUSTOMER_PAYMENTS
    ,COALESCE(I.TOTAL_BILLED, 0) - COALESCE(P.TOTAL_PAID, 0)   AS BALANCE_DUE
FROM CUSTOMERS AS C
LEFT JOIN (SELECT CUSTOMER_ID, SUM(TOTAL_AMOUNT_DUE) AS TOTAL_BILLED FROM INVOICES GROUP BY CUSTOMER_ID) AS I
    ON C.CUSTOMER_ID = I.CUSTOMER_ID
LEFT JOIN (SELECT CUSTOMER_ID, SUM(PAYMENT_AMOUNT) AS TOTAL_PAID FROM CUSTOMER_PAYMENTS GROUP BY CUSTOMER_ID) AS P
    ON C.CUSTOMER_ID = P.CUSTOMER_ID;
GO

-- what Bob owes each supplier: materials bought (quantity x unit cost) minus payments made
CREATE VIEW SUPPLIER_BALANCES AS
SELECT
     S.SUPPLIER_ID
    ,S.SUPPLIER_NAME
    ,COALESCE(M.TOTAL_PURCHASED, 0)                                AS TOTAL_PURCHASED
    ,COALESCE(P.TOTAL_PAID, 0)                                     AS TOTAL_PAID
    ,COALESCE(M.TOTAL_PURCHASED, 0) - COALESCE(P.TOTAL_PAID, 0)    AS BALANCE_OWED
FROM SUPPLIERS AS S
LEFT JOIN (SELECT SUPPLIER_ID, SUM(MATERIAL_QTY * MATERIAL_UNIT_COST) AS TOTAL_PURCHASED FROM MATERIALS GROUP BY SUPPLIER_ID) AS M
    ON S.SUPPLIER_ID = M.SUPPLIER_ID
LEFT JOIN (SELECT SUPPLIER_ID, SUM(PAYMENT_AMOUNT) AS TOTAL_PAID FROM SUPPLIER_PAYMENTS GROUP BY SUPPLIER_ID) AS P
    ON S.SUPPLIER_ID = P.SUPPLIER_ID;
GO
